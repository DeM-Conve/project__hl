// Package gen writes the compose files hl generates: the proxy, and per app
// an override that wires the app to the proxy and keeps its data in the
// homelab folder. The app's own compose files are never edited.
package gen

import (
	"fmt"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/DeM-Conve/project__hl/internal/compose"
	"github.com/DeM-Conve/project__hl/internal/config"
)

const header = "# Generated by hl from hl.yml on every command - edit hl.yml, not this file.\n"

// proxyNet is the override's name for the proxy network, unlikely to clash
// with a network of the app's own.
const proxyNet = "hl-proxy"

// App is everything needed to write one app's override.
type App struct {
	Name    string
	Routing string // path, host or none
	Prefix  string // path routing
	Host    string // host routing
	Service string
	Port    int
	Network string // the proxy's Docker network
	DataDir string // volumes are bind-mounted below it
}

// Override is the compose file layered on top of the app's own.
func Override(a App, m *compose.Model) (string, []string, error) {
	var b strings.Builder
	b.WriteString(header)

	if a.Routing != config.RoutingNone {
		svc, ok := m.Services[a.Service]
		if !ok {
			return "", nil, fmt.Errorf("%s: no service %q in its compose files", a.Name, a.Service)
		}
		id := config.ID(a.Name)
		fmt.Fprintf(&b, "services:\n  %s:\n", a.Service)
		// Reached through the proxy only, so no host port of its own.
		b.WriteString("    ports: !reset []\n")
		b.WriteString("    networks:\n")
		nets := sortedKeys(svc.Networks)
		if len(nets) == 0 {
			nets = []string{"default"}
		}
		// Listed again so adding the proxy network keeps the ones it already has.
		for _, n := range nets {
			fmt.Fprintf(&b, "      %s: {}\n", n)
		}
		fmt.Fprintf(&b, "      %s: {}\n", proxyNet)
		b.WriteString("    labels:\n")
		for _, l := range labels(id, a) {
			fmt.Fprintf(&b, "      %s: %s\n", l[0], quote(l[1]))
		}
		fmt.Fprintf(&b, "networks:\n  %s:\n    name: %s\n    external: true\n", proxyNet, quote(a.Network))
	}

	// Named volumes become folders in the homelab: data/<app>/<volume>.
	var dirs []string
	var vols strings.Builder
	for _, name := range sortedKeys(m.Volumes) {
		v := m.Volumes[name]
		if v.External || (v.Driver != "" && v.Driver != "local") || len(v.DriverOpts) > 0 {
			continue // managed elsewhere: leave it as the app defines it
		}
		dir := filepath.Join(a.DataDir, name)
		dirs = append(dirs, dir)
		fmt.Fprintf(&vols, "  %s:\n    driver: local\n    driver_opts:\n      type: none\n      o: bind\n      device: %s\n", name, quote(dir))
	}
	if vols.Len() > 0 {
		b.WriteString("volumes:\n")
		b.WriteString(vols.String())
	}
	return b.String(), dirs, nil
}

func labels(id string, a App) [][2]string {
	l := [][2]string{
		{"traefik.enable", "true"},
		{"traefik.docker.network", a.Network},
		{"traefik.http.routers." + id + ".entrypoints", "web"},
		{"traefik.http.services." + id + ".loadbalancer.server.port", fmt.Sprint(a.Port)},
	}
	switch a.Routing {
	case config.RoutingHost:
		l = append(l, [2]string{"traefik.http.routers." + id + ".rule", "Host(`" + a.Host + "`)"})
	case config.RoutingPath:
		// /<prefix> redirects to /<prefix>/; the prefix is stripped before the
		// request reaches the app and passed on as X-Forwarded-Prefix.
		re := "^(https?://[^/]+" + regexp.QuoteMeta(a.Prefix) + ")$"
		l = append(l,
			// No Host() match: the app answers on whatever name or address reaches the proxy.
			[2]string{"traefik.http.routers." + id + ".rule", "Path(`" + a.Prefix + "`) || PathPrefix(`" + a.Prefix + "/`)"},
			[2]string{"traefik.http.routers." + id + ".middlewares", id + "-slash," + id + "-strip"},
			[2]string{"traefik.http.middlewares." + id + "-slash.redirectregex.regex", dollar(re)},
			[2]string{"traefik.http.middlewares." + id + "-slash.redirectregex.replacement", dollar("${1}/")},
			[2]string{"traefik.http.middlewares." + id + "-strip.stripprefix.prefixes", a.Prefix},
		)
	}
	return l
}

// Proxy is the compose file for the Traefik container all apps sit behind.
func Proxy(p config.Proxy) string {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("name: hl-proxy\n\nservices:\n  traefik:\n")
	fmt.Fprintf(&b, "    image: %s\n", quote(p.Image))
	b.WriteString("    restart: unless-stopped\n    command:\n")
	for _, c := range []string{
		"--providers.docker=true",
		"--providers.docker.exposedbydefault=false",
		"--providers.docker.network=" + p.Network,
		"--entrypoints.web.address=:80",
		"--api.dashboard=true",
	} {
		fmt.Fprintf(&b, "      - %s\n", quote(c))
	}
	fmt.Fprintf(&b, "    ports:\n      - %s\n", quote(fmt.Sprintf("%s:%d:80", p.Bind, p.Port)))
	b.WriteString("    volumes:\n      - /var/run/docker.sock:/var/run/docker.sock:ro\n")
	b.WriteString("    networks: [proxy]\n    labels:\n")
	b.WriteString("      traefik.enable: 'true'\n")
	fmt.Fprintf(&b, "      traefik.http.routers.hl-dashboard.rule: %s\n", quote("Host(`traefik."+p.Domain+"`)"))
	b.WriteString("      traefik.http.routers.hl-dashboard.service: api@internal\n")
	fmt.Fprintf(&b, "\nnetworks:\n  proxy:\n    name: %s\n", quote(p.Network))
	if p.Subnet != "" {
		fmt.Fprintf(&b, "    ipam:\n      config:\n        - subnet: %s\n", quote(p.Subnet))
	}
	return b.String()
}

// quote is a YAML single-quoted scalar.
func quote(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }

// dollar escapes $ from compose's interpolation.
func dollar(s string) string { return strings.ReplaceAll(s, "$", "$$") }

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
